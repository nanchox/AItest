export const DICTS: Record<Lang, Dict> = { en, es };

export type T = (key: string, vars?: Record<string, string | number>) => string;

export function makeT(lang: Lang): T {
  const d = DICTS[lang] ?? en;
  return (key, vars) => {
    let k = key;
    if (vars && typeof vars.n === "number") {
      const plural = `${key}_${vars.n === 1 ? "one" : "other"}`;
      if (plural in d || plural in en) k = plural;
    }
    let s = d[k] ?? en[k] ?? key;
    if (vars) for (const [name, v] of Object.entries(vars)) s = s.split(`{${name}}`).join(String(v));
    return s;
  };
}

export function ordinal(lang: Lang, n: number): string {
  if (lang === "es") return `${n}.º`;
  const mod100 = n % 100;
  const suffix = mod100 >= 11 && mod100 <= 13 ? "th" : ({ 1: "st", 2: "nd", 3: "rd" } as Record<number, string>)[n % 10] ?? "th";
  return `${n}${suffix}`;
}
